use aes::cipher::{generic_array::GenericArray, BlockEncrypt, KeyInit};
use aes::Aes128;
use thiserror::Error;

#[derive(Error, Debug)]
pub enum CryptoError {
    #[error("Invalid IRK hex string: {0}")]
    InvalidHex(String),
    #[error("Invalid IRK byte length, expected 16 bytes, got {0}")]
    InvalidLength(usize),
}

/// Resolves Bluetooth Low Energy (BLE) Resolvable Private Addresses (RPAs)
/// using an Identity Resolving Key (IRK) according to Bluetooth Core Spec Vol 3, Part H, Sec 2.2.2.
#[derive(Clone)]
pub struct IrkResolver {
    cipher: Aes128,
    irk_bytes: [u8; 16],
}

impl IrkResolver {
    /// Creates an IRK resolver from a 16-byte key.
    pub fn new(irk: &[u8; 16]) -> Self {
        Self {
            cipher: Aes128::new(GenericArray::from_slice(irk)),
            irk_bytes: *irk,
        }
    }

    /// Creates an IRK resolver from a 32-character hexadecimal string (e.g., "ec0234a357c8ad05341010a60a397d9b").
    pub fn from_hex(hex_str: &str) -> Result<Self, CryptoError> {
        let clean = hex_str.trim().replace([':', '-', ' '], "");
        if clean.len() != 32 {
            return Err(CryptoError::InvalidLength(clean.len() / 2));
        }

        let mut bytes = [0u8; 16];
        for i in 0..16 {
            let byte_slice = &clean[i * 2..i * 2 + 2];
            bytes[i] = u8::from_str_radix(byte_slice, 16)
                .map_err(|_| CryptoError::InvalidHex(byte_slice.to_string()))?;
        }

        Ok(Self::new(&bytes))
    }

    /// Returns the raw 16-byte IRK.
    pub fn irk(&self) -> &[u8; 16] {
        &self.irk_bytes
    }

    /// Checks if a 48-bit Bluetooth MAC address is a Resolvable Private Address (RPA)
    /// generated by this IRK.
    pub fn matches_rpa(&self, mac: u64) -> bool {
        // In a 48-bit address (bits 47..0):
        // Bits 47:46 must be 0b01 (Random Resolvable Address)
        let msb = ((mac >> 40) & 0xFF) as u8;
        if (msb & 0xC0) != 0x40 {
            return false;
        }

        // prand = 24 most significant bits (bits 47..24)
        let prand = [
            ((mac >> 40) & 0xFF) as u8,
            ((mac >> 32) & 0xFF) as u8,
            ((mac >> 24) & 0xFF) as u8,
        ];

        // hash = 24 least significant bits (bits 23..0)
        let received_hash = [
            ((mac >> 16) & 0xFF) as u8,
            ((mac >> 8) & 0xFF) as u8,
            (mac & 0xFF) as u8,
        ];

        let computed_hash = self.compute_ah(&prand);
        computed_hash == received_hash
    }

    /// Bluetooth standard `ah(k, r)` address resolution hash function.
    ///
    /// r' is a 128-bit block where the 104 most significant bits are 0
    /// and the 24 least significant bits are prand (r).
    ///
    /// ah(k, r) = e(k, r') truncated to the 24 least significant bits.
    pub fn compute_ah(&self, prand: &[u8; 3]) -> [u8; 3] {
        let mut block = [0u8; 16];
        block[13] = prand[0];
        block[14] = prand[1];
        block[15] = prand[2];

        let mut block_ga = GenericArray::clone_from_slice(&block);
        self.cipher.encrypt_block(&mut block_ga);

        [block_ga[13], block_ga[14], block_ga[15]]
    }
}

/// Helper to format a 48-bit MAC address into a standard hex string (XX:XX:XX:XX:XX:XX).
pub fn format_mac(mac: u64) -> String {
    format!(
        "{:02X}:{:02X}:{:02X}:{:02X}:{:02X}:{:02X}",
        (mac >> 40) & 0xFF,
        (mac >> 32) & 0xFF,
        (mac >> 24) & 0xFF,
        (mac >> 16) & 0xFF,
        (mac >> 8) & 0xFF,
        mac & 0xFF
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_bluetooth_sig_ah_test_vector() {
        // Official Bluetooth Core Specification Test Vector
        // IRK: ec0234a3 57c8ad05 341010a6 0a397d9b
        let irk: [u8; 16] = [
            0xec, 0x02, 0x34, 0xa3, 0x57, 0xc8, 0xad, 0x05,
            0x34, 0x10, 0x10, 0xa6, 0x0a, 0x39, 0x7d, 0x9b,
        ];
        let prand: [u8; 3] = [0x70, 0x81, 0x94];
        let expected_hash: [u8; 3] = [0x0d, 0xfb, aa_to_u8()];

        let resolver = IrkResolver::new(&irk);
        let computed = resolver.compute_ah(&prand);
        assert_eq!(computed, expected_hash);

        // Construct 48-bit RPA: prand (24 bits) || hash (24 bits)
        // prand = 0x708194 (MSB 0x70 has 0b01000000 -> valid RPA)
        let mac: u64 = ((prand[0] as u64) << 40)
            | ((prand[1] as u64) << 32)
            | ((prand[2] as u64) << 24)
            | ((expected_hash[0] as u64) << 16)
            | ((expected_hash[1] as u64) << 8)
            | (expected_hash[2] as u64);

        assert!(resolver.matches_rpa(mac));

        // Tampered MAC must fail
        assert!(!resolver.matches_rpa(mac ^ 1));
    }

    fn aa_to_u8() -> u8 {
        0xaa
    }

    #[test]
    fn test_irk_from_hex() {
        let hex = "ec0234a357c8ad05341010a60a397d9b";
        let resolver = IrkResolver::from_hex(hex).expect("Valid hex");
        assert_eq!(resolver.irk()[0], 0xec);
        assert_eq!(resolver.irk()[15], 0x9b);
    }
}
