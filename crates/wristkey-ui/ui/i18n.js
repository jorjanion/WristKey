let currentLang = localStorage.getItem("wristkey_lang") || "en";

function getCurrentLanguage() {
    return currentLang;
}

function t(key, params = {}) {
    const langDict = TRANSLATIONS[currentLang] || TRANSLATIONS["en"];
    let text = langDict[key] || TRANSLATIONS["en"][key] || key;
    for (const [k, v] of Object.entries(params)) {
        text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), v);
    }
    return text;
}

function setLanguage(lang) {
    if (!TRANSLATIONS[lang]) {
        lang = "en";
    }
    currentLang = lang;
    localStorage.setItem("wristkey_lang", lang);
    document.documentElement.lang = lang;

    const select = document.getElementById("lang-select");
    if (select && select.value !== lang) {
        select.value = lang;
    }

    applyTranslationsToDOM();

    // Trigger re-render of dynamic elements if they exist
    if (typeof updateThresholdMarkers === "function") {
        updateThresholdMarkers();
    }
}

function applyTranslationsToDOM() {
    // Translate textContent for elements with data-i18n
    document.querySelectorAll("[data-i18n]").forEach(el => {
        const key = el.getAttribute("data-i18n");
        if (key) {
            el.innerHTML = t(key);
        }
    });

    // Translate placeholders
    document.querySelectorAll("[data-i18n-ph]").forEach(el => {
        const key = el.getAttribute("data-i18n-ph");
        if (key) {
            el.setAttribute("placeholder", t(key));
        }
    });

    // Translate titles
    document.querySelectorAll("[data-i18n-title]").forEach(el => {
        const key = el.getAttribute("data-i18n-title");
        if (key) {
            el.setAttribute("title", t(key));
        }
    });

    // Update document title
    document.title = t("app.title");
}

// Initialize on script load
document.addEventListener("DOMContentLoaded", () => {
    const select = document.getElementById("lang-select");
    if (select) {
        select.value = currentLang;
        select.addEventListener("change", (e) => {
            setLanguage(e.target.value);
        });
    }
    setLanguage(currentLang);
});
